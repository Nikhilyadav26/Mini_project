export function Sidebar({ activePage, onNavigate }) {
  const { user, logout, switchDemoRole } = useAuth();
  const toast = useToast();
  const isTeacher = user?.role === 'teacher';

  function handleLogout() {
    logout();
    toast.info('Logged out successfully');
  }

  async function handleSwitchRole() {
    try {
      const target = isTeacher ? 'Student' : 'Teacher';
      await switchDemoRole();
      toast.success(`Switched to ${target} section!`);
    } catch (err) {
      toast.error(err.message || 'Failed to switch role');
    }
  }

  const navItems = [
    { id: 'dashboard',      label: 'Dashboard',       icon: Icon.Home },
    { section: 'CAMPUS' },
    { id: 'notices',        label: 'Notices',          icon: Icon.Bell },
    { id: 'announcements',  label: 'Announcements',    icon: Icon.Megaphone },
    { id: 'events',         label: 'Events',           icon: Icon.Calendar },
    { id: 'complaints',     label: 'Complaints',       icon: Icon.MessageSquare },
    { section: 'ACADEMIC' },
    { id: 'assignments',    label: 'Assignments',      icon: Icon.ClipboardList },
    { section: 'AI SIGNATURE' },
    { id: 'roadmap',        label: 'Teaching Roadmap', icon: Icon.Map,      badge: 'AI' },
    { id: 'opportunities',  label: 'Placement Engine', icon: Icon.Briefcase, badge: 'AI' },
  ];

  const initials = user?.name?.split(' ').map(w => w[0]).join('').toUpperCase().slice(0,2) || '??';

  return (
    <nav className="sidebar" id="sidebar">
      <div className="sidebar-logo">
        <div className="sidebar-logo-inner">
          <div className="logo-icon">CC</div>
          <div className="logo-text">
            <h2>Campus Connect</h2>
            <span>Smart College Portal</span>
          </div>
        </div>
      </div>

      <div className="sidebar-nav">
        {navItems.map((item, i) => {
          if (item.section) {
            return <div key={i} className="nav-section-label">{item.section}</div>;
          }
          const IcoCmp = item.icon;
          return (
            <div
              key={item.id}
              id={`nav-${item.id}`}
              className={`nav-item ${activePage === item.id ? 'active' : ''}`}
              onClick={() => onNavigate(item.id)}
              role="button"
              tabIndex={0}
              onKeyDown={e => e.key === 'Enter' && onNavigate(item.id)}
            >
              <IcoCmp />
              <span>{item.label}</span>
              {item.badge && <span className="nav-badge ai-badge">{item.badge} ✦</span>}
            </div>
          );
        })}
      </div>

      <div className="sidebar-user">
        <div className="sidebar-user-inner">
          <div className={`user-avatar ${user?.role}`}>{initials}</div>
          <div className="user-info">
            <strong>{user?.name}</strong>
            <span style={{ display: 'flex', alignItems: 'center', gap: '6px' }}>
              <span className={`badge badge-${user?.role}`} style={{ padding: '1px 6px', fontSize: '10px' }}>
                {user?.role}
              </span>
            </span>
          </div>
          <button className="logout-btn" onClick={handleLogout} title="Sign Out of Campus Connect" id="logout-btn">
            <Icon.LogOut />
            <span>Logout</span>
          </button>
        </div>
        <button
          id="switch-role-btn"
          type="button"
          onClick={handleSwitchRole}
          style={{
            marginTop: '10px',
            width: '100%',
            background: isTeacher ? 'rgba(99,102,241,0.1)' : 'rgba(16,185,129,0.1)',
            border: isTeacher ? '1px solid rgba(99,102,241,0.25)' : '1px solid rgba(16,185,129,0.25)',
            color: isTeacher ? '#818cf8' : '#34d399',
            borderRadius: 'var(--radius-sm)',
            padding: '6px 10px',
            fontSize: '11.5px',
            fontWeight: '600',
            cursor: 'pointer',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'center',
            gap: '6px',
            transition: 'all 0.15s ease',
          }}
          title={isTeacher ? "Switch to Student View" : "Switch to Teacher View"}
        >
          <span>⇄</span> Switch to {isTeacher ? 'Student View' : 'Teacher View'}
        </button>
      </div>
    </nav>
  );
}
